def trend(start=2010):
    """trend = 추세. start년부터 2023년까지 직선을 맞춰 연간 변화(기울기)와 95% 구간, 데이터 점 수를 돌려준다. 구간은 연도별 값이 독립·등분산이라는 회귀 가정 하의 기울기 구간이며 미래 값의 예측구간이 아니다. 점이 적어 넓다."""
    from scipy import stats  # 웹 화면이 이 모듈의 상수만 쓸 때 scipy를 불러오지 않도록 함수 안에서 불러옴
    y = GRID.loc[start:]
    if len(y) < 4:
        raise ValueError("추세는 표본 4개 이상(start<=2020) 필요")
    x = y.index.values.astype(float)
    b, a = np.polyfit(x, y.values, 1)
    n = len(y); se = np.sqrt(((y.values - (a + b * x)) ** 2).sum() / (n - 2) / ((x - x.mean()) ** 2).sum())
    t = stats.t.ppf(0.975, n - 2)  # t 분포 95% 임계값
    return dict(slope=b, lo=b - t * se, hi=b + t * se, n=n, intercept=a)


def scenario(year, kind, floor=0.15):
    """scenario = 전력배출계수 시나리오(예측이 아니라 범위). kind: '정체'(2023 유지), '14년 추세'(2010~2023 직선), '2018 기준 하락 속도'(2018→2023 두 끝점의 차이÷5. 2018은 온실가스 배출 정점 연도이지 계수의 전 기간 최고가 아니며, 낙관 쪽 시나리오). floor 아래로는 내려가지 않게 자른다."""
    g23, k = GRID.loc[2023], year - 2023
    v = {"정체": g23, "14년 추세": g23 + trend(2010)["slope"] * k, "2018 기준 하락 속도": g23 + (GRID.loc[2023] - GRID.loc[2018]) / 5 * k}[kind]
    return max(v, floor)
